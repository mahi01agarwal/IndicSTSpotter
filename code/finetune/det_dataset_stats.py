#!/usr/bin/env python3
"""Measure whether a synthetic dataset has DETECTOR-appropriate layout statistics.

Why this exists
---------------
A recogniser dataset and a detector dataset want opposite things from layout.
Rec training wants many word crops per rendered image, so it pays to tile the
canvas densely. Det training learns a *prior over where and how much text
appears*, so that same dense tiling teaches the detector two false things:

  1. "text covers ~a third of every image"  -> it keeps firing on real photos
     until it has found its expected quota  -> insertion-heavy over-detection.
  2. "regular periodic stroke texture is text" (if the layout is a grid)
     -> corrugated awnings, lattice trusses and window grilles read as text,
     with HIGH confidence, so no box_thresh can separate them.

Our 25k was generated by generate_grid_transforms.py on a 7x6 cell grid with
up to 6 words/cell and only 8% of cells empty. Measured: ~121 words/image at
~32% text area. Real Marathi/Hindi scene photos carry ~11 words/image. That
11x density gap is why the fine-tuned detector over-fires on real images while
scoring 0.962 Hmean on its own synthetic val split -- the val split shares the
defect, so it cannot see it.

Run this on any candidate dataset BEFORE spending GPU hours on it.

Usage
  # synthetic dataset alone
  python det_dataset_stats.py --dataset-dir ~/Desktop/out_dataset_25k_realistic_test

  # compare against the real eval set (word counts come from the eval CSV)
  python det_dataset_stats.py --dataset-dir <synth> \
      --real-csv ~/Desktop/fullpage_real_marathi/after_per_image.csv

  # full real stats incl. area, from the real GT-box JSONs (on ada)
  python det_dataset_stats.py --dataset-dir <synth> --real-dir $SCR/real_marathi
"""
import os
import csv
import json
import glob
import math
import argparse
import statistics as st


# --------------------------------------------------------------- loading
def synth_stats(dataset_dir):
    """words/image + text-area fraction + box centres, from annotations/*.json."""
    ann_dir = os.path.join(dataset_dir, "annotations")
    files = sorted(glob.glob(os.path.join(ann_dir, "*.json")))
    if not files:
        raise SystemExit(f"no annotations under {ann_dir}")

    counts, fracs, per_image_centres = [], [], []
    for path in files:
        ann = json.load(open(path, encoding="utf-8"))
        inst = ann.get("instances", [])
        W = ann.get("width") or 0
        H = ann.get("height") or 0
        area = 0.0
        centres = []
        for i in inst:
            b = i.get("bbox")
            if not b or len(b) < 4:
                continue
            x, y, w, h = b[:4]
            area += w * h
            centres.append((x + w / 2.0, y + h / 2.0))
        counts.append(len(inst))
        if W and H:
            fracs.append(area / float(W * H))
        per_image_centres.append((centres, W, H))
    return counts, fracs, per_image_centres


def real_stats_from_dir(real_dir):
    """words/image + area fraction from real GT-box JSONs {"words":[{x,y,w,h,...}]}."""
    files = sorted(glob.glob(os.path.join(real_dir, "*.json")))
    files = [f for f in files if not os.path.basename(f).startswith("manifest")]
    if not files:
        raise SystemExit(f"no GT JSONs under {real_dir}")
    counts, fracs = [], []
    for path in files:
        gt = json.load(open(path, encoding="utf-8"))
        words = gt.get("words", [])
        # only count words the annotator could actually read
        words = [w for w in words if (w.get("text") or "").strip() not in ("", "NA")]
        counts.append(len(words))
        img = os.path.splitext(path)[0] + ".jpg"
        dims = _image_size(img)
        if dims:
            W, H = dims
            area = sum(float(w.get("w", 0)) * float(w.get("h", 0)) for w in words)
            fracs.append(area / float(W * H))
    return counts, fracs


def _image_size(path):
    """Image dims without a hard PIL dependency at import time."""
    if not os.path.isfile(path):
        return None
    try:
        from PIL import Image
        with Image.open(path) as im:
            return im.size
    except Exception:
        return None


def real_counts_from_csv(csv_path):
    """words/image from an eval_fullpage per-image CSV (ref_words column)."""
    counts = []
    with open(csv_path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row.get("ref_words"):
                counts.append(int(row["ref_words"]))
    if not counts:
        raise SystemExit(f"no ref_words column values in {csv_path}")
    return counts


# --------------------------------------------------------------- regularity
def grid_regularity(per_image_centres, tol_frac=0.02, min_boxes=8):
    """How grid-like is the layout? 0 = scattered, 1 = a perfect lattice.

    Boxes are binned into row bands by y-centre (tolerance = tol_frac of image
    height). A grid puts every box in a few bands whose spacing is near-constant,
    so we score the *evenness* of the gaps between consecutive band centres:
    1 - (stdev(gaps) / mean(gaps)), clamped to [0, 1]. Scattered real text gives
    irregular gaps and scores low; a 7-row lattice scores near 1.
    """
    scores = []
    for centres, W, H in per_image_centres:
        if len(centres) < min_boxes or not H:
            continue
        tol = max(1.0, tol_frac * H)
        bands = []
        for _, cy in sorted(centres, key=lambda c: c[1]):
            if bands and abs(cy - bands[-1][-1]) <= tol:
                bands[-1].append(cy)
            else:
                bands.append([cy])
        if len(bands) < 3:
            continue
        band_centres = [sum(b) / len(b) for b in bands]
        gaps = [band_centres[i + 1] - band_centres[i] for i in range(len(band_centres) - 1)]
        mean_gap = sum(gaps) / len(gaps)
        if mean_gap <= 0:
            continue
        cv = st.pstdev(gaps) / mean_gap
        scores.append(max(0.0, min(1.0, 1.0 - cv)))
    return (st.mean(scores) if scores else float("nan")), len(scores)


# --------------------------------------------------------------- reporting
def describe(name, counts, fracs):
    line = (f"  {name:<22} images={len(counts):<6} "
            f"words/img mean={st.mean(counts):6.1f} median={st.median(counts):5.1f} "
            f"min={min(counts):<4} max={max(counts):<4}")
    if fracs:
        line += f"  text-area mean={st.mean(fracs) * 100:5.1f}%  max={max(fracs) * 100:5.1f}%"
    print(line)


def main():
    ap = argparse.ArgumentParser(
        description="Check a synthetic dataset's layout stats against real scene text.")
    ap.add_argument("--dataset-dir", required=True,
                    help="Synthetic dataset dir (has annotations/).")
    ap.add_argument("--real-dir", default=None,
                    help="Real GT-box JSON dir (full stats incl. text area).")
    ap.add_argument("--real-csv", default=None,
                    help="eval_fullpage per-image CSV (word counts only).")
    ap.add_argument("--target-words", type=float, default=11.0,
                    help="Target mean words/image (default 11 = real Marathi/Hindi).")
    ap.add_argument("--target-area", type=float, default=0.05,
                    help="Target mean text-area fraction (default 0.05).")
    args = ap.parse_args()

    counts, fracs, centres = synth_stats(args.dataset_dir)
    print(f"\n[synthetic] {args.dataset_dir}")
    describe("synthetic", counts, fracs)

    reg, n_reg = grid_regularity(centres)
    if not math.isnan(reg):
        verdict = "LATTICE" if reg >= 0.75 else ("semi-regular" if reg >= 0.5 else "scattered")
        print(f"  {'grid regularity':<22} {reg:.2f} ({verdict}, over {n_reg} images)")
        if reg >= 0.75:
            print("       ^ periodic layout teaches 'repeating stroke texture = text'")
            print("         -> high-confidence false positives on awnings/grilles/trusses")

    real_counts = real_fracs = None
    if args.real_dir:
        real_counts, real_fracs = real_stats_from_dir(args.real_dir)
    elif args.real_csv:
        real_counts, real_fracs = real_counts_from_csv(args.real_csv), []
    if real_counts:
        print(f"\n[real] {args.real_dir or args.real_csv}")
        describe("real", real_counts, real_fracs)

    # ------------------------------------------------------------- verdict
    print("\n[verdict]")
    tgt_w = st.mean(real_counts) if real_counts else args.target_words
    ratio = st.mean(counts) / tgt_w if tgt_w else float("nan")
    print(f"  density ratio (synth / real words-per-image): {ratio:.1f}x")
    if ratio > 2.0:
        print(f"  TOO DENSE -- the detector will learn to expect ~{st.mean(counts):.0f} words")
        print(f"  per image and keep firing on real photos that hold ~{tgt_w:.0f}.")
        print("  This is the over-detection signature (WER > 1, ~2x stock box count).")
    elif ratio < 0.5:
        print("  TOO SPARSE -- the detector will under-fire; expect recall loss.")
    else:
        print("  Density is in a sane range for detector training.")

    if fracs:
        tgt_a = st.mean(real_fracs) if real_fracs else args.target_area
        print(f"  text-area ratio: {st.mean(fracs) / tgt_a:.1f}x  "
              f"(synth {st.mean(fracs) * 100:.1f}% vs target {tgt_a * 100:.1f}%)")


if __name__ == "__main__":
    main()
